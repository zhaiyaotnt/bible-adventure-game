// Tiny deterministic RNG helpers for per-attempt randomization.
// mulberry32: seedable PRNG so tests (and replays) can reproduce a roll.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Fisher–Yates shuffle of [0..n-1] using the given random source.
export function shuffledIndices(n, rand = Math.random) {
  const out = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

export function pickOne(list, rand = Math.random) {
  return list[Math.floor(rand() * list.length)];
}
